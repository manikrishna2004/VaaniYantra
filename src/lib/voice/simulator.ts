import { prisma } from '@/lib/db';
import { getSpeechProvider } from '@/lib/adapters/speech';
import { getLlmProvider, type ChatMessage } from '@/lib/adapters/llm';
import { generateAgentTurn, recordTurn, summarizeCall } from './conversation';
import type { Agent } from '@prisma/client';

// Drives a complete mock call through the real STT->LLM->TTS pipeline without a
// PSTN connection. Used when USE_MOCK_TELEPHONY is on so the dashboard fills
// with realistic calls, transcripts, recordings, and analytics.
//
// It plays both sides: a synthetic "caller" (LLM-driven, given a goal) talks to
// the configured agent. Each turn exercises the speech provider (TTS for the
// agent, STT echo for the caller) and the RAG-backed conversation logic.

const CALLER_GOALS = [
  'You are calling to ask about pricing and want a quick quote. Keep messages to one sentence.',
  'You are calling to ask what the business hours are and whether they are open on weekends. One sentence per turn.',
  'You are calling because you have a question about a product or service. Be brief, one sentence per turn.',
  'You are calling to book or schedule something. Keep it short, one sentence per turn.',
];

export async function runSimulatedCall(callId: string): Promise<void> {
  const call = await prisma.call.findUnique({
    where: { id: callId },
    include: { agent: true },
  });
  if (!call || !call.agent) {
    console.error('[simulator] call or agent missing', callId);
    return;
  }
  const agent = call.agent as Agent;
  const speech = getSpeechProvider();
  const llm = getLlmProvider();

  await prisma.call.update({
    where: { id: callId },
    data: { status: 'IN_PROGRESS', startedAt: new Date() },
  });

  const start = Date.now();
  const ms = () => Date.now() - start;

  const goal = CALLER_GOALS[Math.floor(Math.random() * CALLER_GOALS.length)];
  const callerSystem = `You are a person making a phone call to a business. ${goal} Respond naturally as the caller. When your question is answered, thank them and say goodbye.`;

  // History from the AGENT's perspective: caller = "user", agent = "model".
  const agentHistory: ChatMessage[] = [];
  // History from the CALLER's perspective is the mirror image.
  const callerHistory: ChatMessage[] = [];

  try {
    // 1. Agent greeting.
    const greeting = agent.greeting?.trim() || 'Hello! Thank you for calling. How can I help you today?';
    await speech.synthesize({ text: greeting, languageCode: agent.language, voiceId: agent.voice });
    await recordTurn(callId, 'AGENT', greeting, ms());
    agentHistory.push({ role: 'model', text: greeting });
    callerHistory.push({ role: 'user', text: greeting });

    const MAX_TURNS = 5;
    for (let turn = 0; turn < MAX_TURNS; turn++) {
      // 2. Caller speaks (synthetic). Generated by the LLM playing the caller.
      const callerText = (
        await llm.generate({
          systemInstruction: callerSystem,
          history: callerHistory,
          temperature: 0.7,
          maxOutputTokens: 80,
        })
      ).trim();

      // Run it "through" STT (echo in mock; real recognize in prod-ish).
      const stt = await speech.transcribe(Buffer.from(callerText, 'utf8'), agent.language);
      const heard = stt.text || callerText;

      await recordTurn(callId, 'CALLER', heard, ms());
      agentHistory.push({ role: 'user', text: heard });
      callerHistory.push({ role: 'model', text: heard });

      if (/\b(bye|goodbye|thank you|thanks|that's all)\b/i.test(heard) && turn > 0) {
        break;
      }

      // 3. Agent replies (RAG-backed, streamed), then TTS.
      const reply = await generateAgentTurn({ agent, history: agentHistory.slice(0, -1), callerText: heard });
      await speech.synthesize({ text: reply, languageCode: agent.language, voiceId: agent.voice });

      await recordTurn(callId, 'AGENT', reply, ms());
      agentHistory.push({ role: 'model', text: reply });
      callerHistory.push({ role: 'user', text: reply });
    }

    const durationSec = Math.max(1, Math.round((Date.now() - start) / 1000));
    const summary = await summarizeCall(callId);

    await prisma.call.update({
      where: { id: callId },
      data: {
        status: 'COMPLETED',
        endedAt: new Date(),
        durationSec,
        summary,
        // Mock recordings point at a placeholder; real calls store provider URLs.
        recordingUrl: `/api/calls/${callId}/recording`,
        endedReason: 'completed',
      },
    });
  } catch (err) {
    console.error('[simulator] failed', err);
    await prisma.call.update({
      where: { id: callId },
      data: { status: 'FAILED', endedAt: new Date(), endedReason: 'error' },
    });
  }
}
